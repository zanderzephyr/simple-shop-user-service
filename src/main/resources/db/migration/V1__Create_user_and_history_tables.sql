CREATE TABLE [User] (
	Id BIGINT IDENTITY(1,1) PRIMARY KEY,
	Username NVARCHAR(30) NOT NULL UNIQUE,
	FirstName NVARCHAR(30) NOT NULL,
	MiddleNames NVARCHAR(100) NULL,
	LastName NVARCHAR(30) NOT NULL,
	Email VARCHAR(254) NOT NULL UNIQUE,
	UserType VARCHAR(20) NOT NULL,
	SrpSalt VARCHAR(128) NOT NULL,
	SrpVerifier VARCHAR(1024) NOT NULL,
	LastChange DATETIME2 NOT NULL,
	LastChangedBy BIGINT NOT NULL CONSTRAINT CHECK_USER_LAST_CHANGED_BY CHECK (LastChangedBy > 0),
	Version BIGINT NOT NULL DEFAULT 0
 );
 
 CREATE TABLE UserHistoryState (
 	Id BIGINT IDENTITY(1,1) PRIMARY KEY,
	UserId BIGINT NOT NULL CONSTRAINT ID_CHECK CHECK (UserId > 0),
	Username NVARCHAR(30) NOT NULL,
	FirstName NVARCHAR(30) NOT NULL,
	MiddleNames NVARCHAR(100) NOT NULL,
	LastName NVARCHAR(30) NOT NULL,
	Email VARCHAR(254) NOT NULL,
	UserType VARCHAR(20) NOT NULL,
	LastChange DATETIME2 NOT NULL,
	LastChangedBy BIGINT NOT NULL CONSTRAINT CHECK_USER_HISTORY_LAST_CHANGED_BY CHECK (LastChangedBy > 0),
	Action VARCHAR(10) NOT NULL,
	Version BIGINT NOT NULL
 );